#!/usr/bin/env python3
"""Turn a pip freeze of the resolved venv into requirements.txt: every distribution pinned with the sha256 of each
PyPI wheel of that version that a CPython 3.14 x86_64 glibc system can install (cp314, abi3, or py3-none; manylinux
x86_64 or any). pip then installs in hash-checking mode, so a missing pin or a changed file fails the build.

    python lock.py requirements.in freeze.txt > requirements.txt      (lock.sh runs this inside aces-builder)
"""
from __future__ import annotations

import json
import re
import sys
import urllib.request

PY_MINOR = 14


def canon(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def pins(path: str) -> dict:
    out = {}
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if "==" in line:
            n, v = line.split("==", 1)
            out[canon(n)] = (n.strip(), v.strip())
    return out


def compatible(filename: str) -> bool:
    if not filename.endswith(".whl"):
        return False
    parts = filename[:-4].split("-")
    py, abi, plat = parts[-3], parts[-2], parts[-1]
    pys, abis, plats = set(py.split(".")), set(abi.split(".")), set(plat.split("."))
    plat_ok = "any" in plats or any(p.startswith("manylinux") and p.endswith("_x86_64") for p in plats)
    if not plat_ok:
        return False
    if f"cp3{PY_MINOR}" in pys and f"cp3{PY_MINOR}" in abis:
        return True
    if "abi3" in abis:
        return any(re.fullmatch(r"cp3(\d+)", p) and int(p[3:]) <= PY_MINOR for p in pys)
    return "none" in abis and bool(pys & {"py3", f"py3{PY_MINOR}", f"cp3{PY_MINOR}"})


def hashes(name: str, version: str) -> list:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as r:
        data = json.load(r)
    return sorted({f["digests"]["sha256"] for f in data["urls"] if compatible(f["filename"])})


def main(argv: list) -> int:
    top = pins(argv[1])
    frozen = pins(argv[2])
    missing = sorted(set(top) - set(frozen))
    if missing:
        print(f"lock.py: top-level pins not in the freeze: {missing}", file=sys.stderr)
        return 1
    lines = ["# GENERATED by lock.sh from requirements.in: do not edit by hand.",
             "# Full lock of the aces-engineering venv (Arch, CPython 3.14, x86_64): every distribution pinned, with the",
             "# sha256 of each compatible PyPI wheel. The build installs it with --require-hashes --only-binary=:all:.", ""]
    for section, keys in (("top-level pins (requirements.in)", [k for k in sorted(frozen) if k in top]),
                          ("resolved dependencies", [k for k in sorted(frozen) if k not in top])):
        lines.append(f"# {section}")
        for k in keys:
            name, ver = frozen[k]
            hs = hashes(name, ver)
            if not hs:
                print(f"lock.py: no compatible wheel on PyPI for {name}=={ver}", file=sys.stderr)
                return 1
            lines.append(f"{name}=={ver} \\")
            lines += [f"    --hash=sha256:{h}" + (" \\" if i < len(hs) - 1 else "") for i, h in enumerate(hs)]
        lines.append("")
    sys.stdout.write("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
