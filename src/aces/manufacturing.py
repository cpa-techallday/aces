def get(process_id: str) -> Process:
    try:
        return PROCESSES[process_id]
    except KeyError:
        raise KeyError(f"unknown manufacturing process {process_id!r}; known: {sorted(PROCESSES)}") from None


def require(process_id: str, domain: str) -> Process:
    """The process, if it is available and supported by ``domain``; otherwise a clear error."""
    p = get(process_id)
    if p.status != "available":
        raise ValueError(f"process {process_id!r} is {p.status} in ACES: {p.notes}")
    if domain not in p.domains:
        ok = sorted(k for k, v in PROCESSES.items() if domain in v.domains and v.status == "available")
        raise ValueError(f"process {process_id!r} is not supported by {domain}; use one of {ok}")
    return p


def for_domain(domain: str) -> list[str]:
    return sorted(k for k, v in PROCESSES.items() if domain in v.domains and v.status == "available")
