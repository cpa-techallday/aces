"""Build the ACES OS integrations catalog from the research workflow journal.

Reads every domain-sweep result in the workflow's journal.jsonl, dedupes rows by repository, and writes
  research/integrations.json   (machine-readable, every row with its verification fields)
  research/INTEGRATIONS.md     (human-readable, grouped by domain)
Usage:  python build_catalog.py <journal.jsonl> [<workflow result json>]
The optional second file is the workflow's returned object (audit + critic), appended to the markdown.
"""
import io
import json
import sys
from collections import OrderedDict

HERE = __file__.rsplit("\\", 1)[0] if "\\" in __file__ else __file__.rsplit("/", 1)[0]
journal = sys.argv[1]
result_file = sys.argv[2] if len(sys.argv) > 2 else None

domains = OrderedDict()
for line in io.open(journal, encoding="utf-8"):
    try:
        j = json.loads(line)
    except Exception:
        continue
    if j.get("type") != "result":
        continue
    r = j.get("result")
    if not isinstance(r, dict) or "rows" not in r:
        continue
    key = r.get("key") or r.get("domain") or "unknown"
    domains[key] = r

# hand-verified row files (one JSON object per file, same shape as an agent result) merge in after the journal
import glob
import os
for extra in sorted(glob.glob(os.path.join(HERE, "extra_rows", "*.json"))):
    try:
        r = json.load(io.open(extra, encoding="utf-8"))
    except Exception as e:  # noqa: BLE001
        print("skipping", extra, e)
        continue
    key = r.get("key") or os.path.basename(extra).rsplit(".", 1)[0]
    if key not in domains:
        domains[key] = r

seen = {}
rows = []
dupes = 0
for key, r in domains.items():
    for row in r.get("rows", []):
        k = str(row.get("repo_or_url") or row.get("name")).lower().strip()
        k = k.replace("https://", "").replace("http://", "").rstrip("/")
        if k in seen:
            dupes += 1
            continue
        seen[k] = key
        row = dict(row)
        row["domain"] = key
        rows.append(row)

# operator policy: research/policy_mode.json {"mode": "trial"} re-tags every "exclude" row as installable for the
# operator's own machines; the audited rules remain the distribution policy for anything shipped to a customer
policy_path = os.path.join(HERE, "policy_mode.json")
policy = {"mode": "distribution"}
if os.path.exists(policy_path):
    try:
        policy = json.load(io.open(policy_path, encoding="utf-8"))
    except Exception as e:  # noqa: BLE001
        print("policy_mode.json unreadable:", e)
TRIAL = str(policy.get("mode", "")).lower() == "trial"
retagged = 0
if TRIAL:
    for row in rows:
        if str(row.get("fit", "")).lower() == "exclude":
            row["fit"] = "trial (operator override; was: exclude)"
            retagged += 1

PERMISSIVE = {"MIT", "APACHE-2.0", "BSD-2-CLAUSE", "BSD-3-CLAUSE", "MPL-2.0", "ISC", "UNLICENSE", "CC0-1.0", "0BSD",
              "ZLIB", "BSL-1.0", "LGPL-2.1", "LGPL-3.0", "LGPL-2.1-OR-LATER", "LGPL-3.0-OR-LATER", "BSD-3-CLAUSE-CLEAR",
              "PSF-2.0", "OFL-1.1", "MIT OR APACHE-2.0", "APACHE-2.0 OR MIT"}

def flag(lic):
    return "" if str(lic or "").upper() in PERMISSIVE else " ⚠"

out = []
out.append("# ACES OS — open-source enhancements and integrations (verified catalog)\n")
out.append("Generated by `research/build_catalog.py` from the research workflow of 2026-10-08. Each row was checked by an agent "
           "against the GitHub API (licence, stars, last push, archived flag), PyPI, the Arch repositories or the AUR; the "
           "`verified` column names the check that succeeded. ⚠ marks a licence that is not plainly permissive (copyleft, "
           "model licence, commercial or unknown) and needs the licence policy in VISION.md Appendix A. `fit` is the agent's "
           "placement: day-one, v1, later or exclude. Nothing here is a commitment; it is the considered set.\n")
out.append(f"Rows: {len(rows)} unique across {len(domains)} domains ({dupes} duplicates removed).\n")
if TRIAL:
    out.append(f"**Policy mode: trial (operator override, Aaron 2026-10-09).** Every row is installable on the operator's own "
               f"machines; {retagged} rows the licence audit excluded are re-tagged `trial` and keep their terms as labels. The "
               f"audited rules at the end of this file are the distribution policy and apply only to what ACES ships to a "
               f"customer. No component is restricted while a project is personal, education or research use with no contract, "
               f"customer, paid deliverable or defence end use (all current projects); terms are re-read at the end-use gate "
               f"when a project changes class.\n")
else:
    out.append("**Policy mode: distribution.** Rows marked exclude are not shipped.\n")

verified = sum(1 for r in rows if str(r.get("verified_via", "none")).lower() not in ("none", ""))
out.append(f"Verified rows: {verified} / {len(rows)}.\n")

for key, r in domains.items():
    out.append(f"\n## {key}\n")
    if r.get("notes"):
        out.append(r["notes"].strip() + "\n")
    out.append("| Name | Adds | Pillar | Licence | Verified | Stars | Pushed | Packaging | Fit | Gotcha |")
    out.append("|---|---|---|---|---|---|---|---|---|---|")
    for row in rows:
        if row["domain"] != key:
            continue
        name = row.get("name", "")
        url = row.get("repo_or_url", "")
        link = f"[{name}]({url})" if str(url).startswith("http") else f"{name} ({url})" if url else name
        stars = row.get("stars")
        stars = "" if stars in (None, "", 0) else f"{int(stars):,}"
        pushed = str(row.get("pushed") or "")[:10]
        arch = " (archived)" if row.get("archived") else ""
        cells = [link, row.get("adds", ""), row.get("pillar", ""), f"{row.get('licence', '')}{flag(row.get('licence'))}",
                 row.get("verified_via", ""), stars, pushed + arch, row.get("packaging", ""), row.get("fit", ""),
                 row.get("gotcha", "")]
        out.append("| " + " | ".join(str(c).replace("|", "/").replace("\n", " ") for c in cells) + " |")
    unv = r.get("unverified_candidates") or []
    if unv:
        out.append("\nUnverified candidates for a human to check: " + "; ".join(unv) + "\n")

# the audit and critic results are also recorded in the journal as their own result lines
audit_j = {}
critic_j = {}
for line in io.open(journal, encoding="utf-8"):
    try:
        j = json.loads(line)
    except Exception:
        continue
    if j.get("type") != "result" or not isinstance(j.get("result"), dict):
        continue
    r = j["result"]
    if "verdicts" in r:
        audit_j = r
    elif "missing" in r:
        critic_j = r

if result_file or audit_j or critic_j:
    try:
        if result_file:
            raw = io.open(result_file, encoding="utf-8").read()
            d = json.loads(raw[raw.find("{"):raw.rfind("}") + 1])
        else:
            d = {}
        audit = d.get("audit") or audit_j
        critic = d.get("critic") or critic_j
        out.append("\n## Licence audit (agent)\n")
        if audit.get("rules"):
            out.append(audit["rules"].strip() + "\n")
        if audit.get("verdicts"):
            out.append("| Component | Licence | Consequence |")
            out.append("|---|---|---|")
            for v in audit["verdicts"]:
                out.append(f"| {v.get('name','')} | {v.get('licence','')} | {str(v.get('consequence','')).replace('|','/')} |")
        out.append("\n## Completeness critic (agent)\n")
        if critic.get("verdict"):
            out.append(critic["verdict"].strip() + "\n")
        if critic.get("missing"):
            out.append("Missing candidates to consider:\n")
            for m in critic["missing"]:
                out.append(f"- **{m.get('name','')}** ({m.get('domain','')}): {m.get('why','')}")
        if critic.get("overlaps_to_resolve"):
            out.append("\nOverlaps to resolve:\n")
            for o in critic["overlaps_to_resolve"]:
                out.append(f"- {o}")
    except Exception as e:  # noqa: BLE001
        out.append(f"\n(Workflow result file could not be parsed: {e})\n")

md_path = HERE + "/INTEGRATIONS.md"
json_path = HERE + "/integrations.json"
io.open(md_path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
io.open(json_path, "w", encoding="utf-8", newline="\n").write(json.dumps({"rows": rows, "domains": {k: {"notes": v.get("notes"), "unverified": v.get("unverified_candidates")} for k, v in domains.items()}}, indent=1, ensure_ascii=False))

by_fit = {}
by_flag = 0
for r in rows:
    by_fit[r.get("fit", "?")] = by_fit.get(r.get("fit", "?"), 0) + 1
    if flag(r.get("licence")):
        by_flag += 1
print(f"domains={len(domains)} rows={len(rows)} dupes={dupes} verified={verified} flagged_licence={by_flag} fit={by_fit}")
print("wrote", md_path, "and", json_path)
